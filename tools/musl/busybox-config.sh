#!/bin/sh
# 用法：bbconfig.sh <.config>   —— 在 defconfig 的基础上调成「安卓应用沙箱里的工具箱」
set -eu
cfg="$1"

off() { for o in "$@"; do sed -i "s/^CONFIG_$o=y\$/# CONFIG_$o is not set/" "$cfg"; done; }
on()  { for o in "$@"; do
          if grep -q "^# CONFIG_$o is not set\$" "$cfg"; then
            sed -i "s/^# CONFIG_$o is not set\$/CONFIG_$o=y/" "$cfg"
          elif ! grep -q "^CONFIG_$o=y\$" "$cfg"; then
            echo "CONFIG_$o=y" >> "$cfg"
          fi
        done; }

# 静态链接；shell 里所有 applet 直接可用，不依赖 PATH 里的软链
on STATIC FEATURE_PREFER_APPLETS FEATURE_SH_STANDALONE FEATURE_SH_NOFORK
on BASH_IS_ASH FEATURE_SH_EXTRA_QUIET AR INSTALL_NO_USR
off BASH_IS_NONE PIE

# 应用进程调 setuid 一族会被 seccomp 直接杀掉；utmp / syslog 在安卓上不存在
off FEATURE_SUID FEATURE_SUID_CONFIG FEATURE_SUID_CONFIG_QUIET
off FEATURE_UTMP FEATURE_WTMP FEATURE_SYSLOG_INFO FEATURE_SYSLOG
off USE_BB_PWD_GRP USE_BB_SHADOW USE_BB_CRYPT USE_BB_CRYPT_SHA
off ASH_MAIL ASH_IDLE_TIMEOUT FEATURE_WGET_OPENSSL FEATURE_HTTPD_SETUID

# 需要 root、内核模块、块设备或硬件的东西：在沙箱里只会报错
off CHVT DEALLOCVT DUMPKMAP FGCONSOLE KBD_MODE LOADFONT SETFONT LOADKMAP OPENVT \
    SETCONSOLE SETKEYCODES SETLOGCONS SHOWKEY RESUME RUN_INIT BOOTCHARTD HALT \
    POWEROFF REBOOT INIT LINUXRC START_STOP_DAEMON CHROOT WHO W USERS
off ADD_SHELL REMOVE_SHELL ADDGROUP ADDUSER CHPASSWD CRYPTPW MKPASSWD DELUSER \
    DELGROUP GETTY LOGIN LOGIN_SCRIPTS PASSWD SU SULOGIN VLOCK
off CHATTR FSCK LSATTR MODPROBE_SMALL DEPMOD INSMOD LSMOD MODINFO MODPROBE RMMOD
off ACPID BLKDISCARD BLKID BLOCKDEV DMESG EJECT FATATTR FBSET FDFORMAT FDISK \
    FINDFS FDFLUSH FREERAMDISK FSCK_MINIX FSFREEZE FSTRIM HWCLOCK IPCRM IPCS LAST \
    LOSETUP LSPCI LSUSB MDEV MESG MKE2FS MKFS_EXT2 MKFS_MINIX MKDOSFS MKFS_VFAT \
    MKSWAP MOUNT MOUNTPOINT NOLOGIN NSENTER PIVOT_ROOT RDATE RDEV READPROFILE \
    RTCWAKE SETARCH LINUX32 LINUX64 SETPRIV SWAPON SWAPOFF SWITCH_ROOT UEVENT \
    UMOUNT UNSHARE WALL VOLUMEID
off ADJTIMEX BEEP CHAT CONSPY CROND CRONTAB DEVMEM FBSPLASH HDPARM I2CGET I2CSET \
    I2CDUMP I2CDETECT I2CTRANSFER LSSCSI MAKEDEVS MAN MICROCOM MIM MT NANDWRITE \
    NANDDUMP PARTPROBE RAIDAUTORUN READAHEAD RUNLEVEL RX SEEDRNG SETSERIAL \
    UBIATTACH UBIDETACH UBIMKVOL UBIRMVOL UBIRSVOL UBIUPDATEVOL UBIRENAME VOLNAME \
    WATCHDOG
off ARP ARPING BRCTL DNSD ETHER_WAKE FTPD IFENSLAVE IFPLUGD IFUP IFDOWN INETD \
    IPTUNNEL IPRULE IPNEIGH FAKEIDENTD NAMEIF NBDCLIENT NTPD ROUTE SLATTACH TC \
    TCPSVD UDPSVD TELNETD TFTPD TRACEROUTE TRACEROUTE6 TUNCTL VCONFIG ZCIP UDHCPD \
    DUMPLEASES DHCPRELAY UDHCPC UDHCPC6
off LPD LPR LPQ MAKEMIME POPMAILDIR REFORMIME SENDMAIL
off KILLALL5 POWERTOP SMEMCAP BB_SYSCTL
off CHPST SETUIDGID ENVUIDGID ENVDIR SOFTLIMIT RUNSV RUNSVDIR SV SVC SVOK SVLOGD
# SHA 硬件加速只有 x86 的实现，1.37.0 在其它架构上开着会编不过；两个 ABI 保持同一份配置
off SHA1_HWACCEL SHA256_HWACCEL
off HUSH SHELL_HUSH CTTYHACK KLOGD LOGGER LOGREAD SYSLOGD DPKG RPM
